#!/usr/bin/env python3
"""Write docs/sku-wise-print-slot-mapping.md from the SKU WISE PRINT xlsx."""
from __future__ import annotations

import importlib.util
import sys
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "docs" / "sku-wise-print-slot-mapping.md"

spec = importlib.util.spec_from_file_location(
    "uat_sku_import",
    REPO / "deploy/scripts/prod-sku-wise-print-import.py",
)
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)

xlsx = next(p for p in mod.XLSX_CANDIDATES if p.exists())
if not xlsx:
    raise SystemExit("SKU WISE PRINT xlsx not found in repo root")

print_name_map = mod.build_print_name_map(xlsx)
parsed = mod.parse_xlsx(xlsx)

style_prints: dict[str, dict[int, str]] = defaultdict(dict)
style_meta: dict[str, dict] = {}
rows_by_style: dict[str, list] = defaultdict(list)

for row in parsed["main"]:
    style = str(row.get("Style Name") or "").strip()
    if not style:
        continue
    rows_by_style[style].append(row)
    style_meta[style] = {
        "parent_sku": mod.parent_sku(style),
        "category": str(row.get("CATEGORY") or "").strip(),
    }

for style, rows in rows_by_style.items():
    row_nums = {r.get("_excelRow") for r in rows if r.get("_excelRow")}
    slots_with_qty: set[int] = set()
    for row in rows:
        for i in range(1, 12):
            if row.get(f"Print-{i} QUANTITY") not in ("", None):
                slots_with_qty.add(i)
    for i in range(1, 12):
        if i not in slots_with_qty:
            continue
        resolved: str | None = None
        for excel_row in sorted(row_nums):
            name = print_name_map.get((excel_row, i))
            if name:
                resolved = name
                break
        if resolved:
            style_prints[style][i] = resolved
            continue
        for row in rows:
            if row.get(f"Print-{i} QUANTITY") in ("", None):
                continue
            cell = str(row.get(f"Print-{i}") or "").strip()
            if cell and cell.upper() != "NO STOCK":
                resolved = cell
                break
        if resolved:
            style_prints[style][i] = resolved

for style_key, whc_name in mod.WHC_STYLE_KEYS.items():
    style = next((n for n in style_meta if mod.norm_key(n) == style_key), None)
    if not style:
        continue
    colors: list[str] = []
    seen: set[str] = set()
    for entry in parsed["whc"].get(whc_name, []):
        c = str(entry["color"]).strip()
        if c and c not in seen:
            seen.add(c)
            colors.append(c)
    if colors:
        style_prints[style] = {i + 1: c for i, c in enumerate(colors)}

lines = [
    "# SKU-wise print slot mapping (Print-1 → print name)",
    "",
    f"**Source:** `{xlsx.name}`",
    "**Generated by:** `deploy/scripts/generate-print-slot-mapping.py`",
    "",
    "Print columns on the main sheet hold **swatch photos only**; names below are resolved by matching those photos to the **PRINT NAMES** sheet (plus `PRINT_NAME_MANUAL_OVERRIDES`).",
    "",
    "**Side button T Shirt (Half sleeve)** uses the **WHC 21-7-26** sheet — slots are WHC colour order, not main-sheet Print-N photos.",
    "",
    "## Quick reference",
    "",
    "| Parent SKU | Print-1 | Print-2 | Print-3 | Print-4 | Print-5 | Print-6+ |",
    "|------------|---------|---------|---------|---------|---------|----------|",
]

for style in sorted(style_prints, key=lambda s: s.lower()):
    psku = style_meta.get(style, {}).get("parent_sku") or mod.parent_sku(style)
    slots = style_prints[style]
    cols = [slots.get(i, "—") for i in range(1, 6)]
    extra = ", ".join(f"Print-{i}: {slots[i]}" for i in sorted(slots) if i >= 6) or "—"
    lines.append(f"| `{psku}` | {cols[0]} | {cols[1]} | {cols[2]} | {cols[3]} | {cols[4]} | {extra} |")

lines.extend(["", "---", ""])

for style in sorted(style_prints, key=lambda s: s.lower()):
    meta = style_meta.get(style, {})
    psku = meta.get("parent_sku") or mod.parent_sku(style)
    cat = meta.get("category", "")
    lines.append(f"## {style}")
    lines.append("")
    lines.append("| Field | Value |")
    lines.append("|-------|-------|")
    lines.append(f"| Parent SKU | `{psku}` |")
    if cat:
        lines.append(f"| Category | {cat} |")
    lines.append("")
    lines.append("| Print slot | Print name |")
    lines.append("|------------|------------|")
    for i in sorted(style_prints[style]):
        lines.append(f"| Print-{i} | {style_prints[style][i]} |")
    lines.append("")

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"Wrote {OUT} ({len(style_prints)} products)")
